import logging
import re

class RiskAssessor:
    """
    Evaluates the raw bash/script generated by the LLM for destructive commands.
    """
    def __init__(self):
        self.logger = logging.getLogger(__name__)
        # List of highly dangerous keywords that require human approval
        self.destructive_patterns = [
            r"\brm\s+-rf\b",
            r"\bdrop\s+table\b",
            r"\bdrop\s+database\b",
            r"\breboot\b",
            r"\bshutdown\b",
            r"\bkillall\b",
            r"\bmkfs\b",
            r"\bfdisk\b",
            r">\s*/dev/null", # Sometimes hides errors
            r"\bsudo\b" # Elevating privileges is inherently risky
        ]

    def assess(self, proposed_fix: str) -> dict:
        """
        Calculates a Risk Score (0-100).
        Returns a dict indicating if it's safe for Auto-Remediation.
        """
        if "ERROR" in proposed_fix or "MANUAL_INTERVENTION_REQUIRED" in proposed_fix:
            return {"is_safe": False, "risk_score": 100, "reason": "Model failed to generate a fix or requested manual intervention."}

        risk_score = 0
        detected_risks = []
        
        # Simple heuristic check
        lower_fix = proposed_fix.lower()
        for pattern in self.destructive_patterns:
            if re.search(pattern, lower_fix):
                risk_score += 50 # Any destructive command heavily penalizes the score
                detected_risks.append(pattern.replace(r"\b", "").replace(r"\s+", " ").strip())

        # If it's a very long script, it's inherently riskier
        if len(proposed_fix.split('\n')) > 10:
            risk_score += 20
            detected_risks.append("script_too_long")

        # Cap risk score at 100
        risk_score = min(100, risk_score)
        
        # We only auto-remediate if the risk is extremely low
        is_safe = risk_score < 30
        
        reason = "Passed safety checks." if is_safe else f"Detected dangerous patterns: {', '.join(detected_risks)}"
        
        self.logger.info(f"Risk Assessment: {risk_score}/100. Safe to auto-remediate? {is_safe}")
        
        return {
            "is_safe": is_safe,
            "risk_score": risk_score,
            "reason": reason
        }
