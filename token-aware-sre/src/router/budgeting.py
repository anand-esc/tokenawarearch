import logging

class TokenBudgeter:
    """Calculates the maximum allowable API spend based on Incident Severity.
    
    This module restricts low-severity incidents to a $0.00 budget (forcing Local SLM routing)
    and allocates higher budgets (Cloud LLM routing) for critical failures.

    Attributes:
        logger (logging.Logger): Logger for the budgeter.
        cost_per_1k_tokens (float): The baseline cost calculation metric (defaulted to GPT-4).
    """
    def __init__(self, cost_per_1k_tokens=0.01):
        self.logger = logging.getLogger(__name__)
        self.cost_per_1k_tokens = cost_per_1k_tokens

    def calculate_budget(self, severity: int) -> dict:
        """Translates a severity score (1-10) into a strict financial token limit.

        Args:
            severity (int): The numerical severity score generated by the Classifier.

        Returns:
            dict: Configuration containing 'max_spend_usd', 'max_tokens', and a 
                  boolean 'requires_local_only'.
        """
        try:
            # Ensure severity is bounded between 1 and 10
            severity = max(1, min(10, int(severity)))
        except (ValueError, TypeError):
            self.logger.error("Invalid severity score provided. Defaulting to 5.")
            severity = 5
        
        # Budget logic curve
        if severity <= 3:
            max_spend_usd = 0.0
        elif severity <= 6:
            max_spend_usd = (severity - 3) * 0.5
        elif severity <= 8:
            max_spend_usd = (severity - 6) * 2.5 + 1.5
        else:
            max_spend_usd = (severity - 8) * 5.0 + 6.5

        # Calculate rough token limit based on max spend
        if max_spend_usd == 0.0:
            token_limit = 0
        else:
            token_limit = int((max_spend_usd / self.cost_per_1k_tokens) * 1000)

        budget_config = {
            "max_spend_usd": round(max_spend_usd, 2),
            "max_tokens": token_limit,
            "requires_local_only": max_spend_usd == 0.0
        }
        
        self.logger.info(f"Severity {severity} -> Budget: ${budget_config['max_spend_usd']} ({budget_config['max_tokens']} tokens)")
        return budget_config

if __name__ == "__main__":
    budgeter = TokenBudgeter()
    for s in range(1, 11):
        print(f"Severity {s}:", budgeter.calculate_budget(s))
